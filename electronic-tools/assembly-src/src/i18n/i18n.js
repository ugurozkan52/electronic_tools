  // Elements whose content is rich HTML carry their English version in data-en.
  let lang = 'tr';
  function setLang(l) { lang = l === 'en' ? 'en' : 'tr'; }
  function getLang() { return lang; }
  function locale() { return lang === 'en' ? 'en-GB' : 'tr-TR'; }
  function fill(s, vars) {
    if (!vars) return s;
    return s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined && vars[k] !== null ? String(vars[k]) : m));
  }
  function t(s, vars) {
    if (s === undefined || s === null) return s;
    const str = String(s);
    const out = lang === 'en' && Object.prototype.hasOwnProperty.call(EN, str) ? EN[str] : str;
    return fill(out, vars);
  }
  // Translate static DOM: text nodes, placeholder/title attributes, data-en blocks.
  function translateDom(rootEl) {
    if (lang !== 'en' || !rootEl) return;
    const doc = rootEl.ownerDocument || rootEl;
    rootEl.querySelectorAll && rootEl.querySelectorAll('[data-en]').forEach((e) => { e.innerHTML = e.getAttribute('data-en'); });
    const walker = doc.createTreeWalker(rootEl, 4 /* SHOW_TEXT */);
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    for (const n of nodes) {
      const p = n.parentNode;
      if (p && (p.nodeName === 'SCRIPT' || p.nodeName === 'STYLE')) continue;
      const raw = n.nodeValue;
      const key = raw.trim();
      if (key && Object.prototype.hasOwnProperty.call(EN, key)) n.nodeValue = raw.replace(key, EN[key]);
    }
    rootEl.querySelectorAll && rootEl.querySelectorAll('[placeholder],[title],[aria-label]').forEach((e) => {
      for (const a of ['placeholder', 'title', 'aria-label']) {
        const v = e.getAttribute(a);
        if (v && Object.prototype.hasOwnProperty.call(EN, v)) e.setAttribute(a, EN[v]);
      }
    });
  }
